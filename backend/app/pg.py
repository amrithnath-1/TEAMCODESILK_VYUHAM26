class Row(dict):
    """Reads by name or position, like sqlite3.Row."""
    __slots__ = ("values_",)

    def __getitem__(self, key):
        return self.values_[key] if isinstance(key, int) else dict.__getitem__(self, key)


def _row_factory(cursor):
    names = [c.name for c in cursor.description] if cursor.description else []

    def make(values):
        row = Row(zip(names, values))
        row.values_ = values
        return row
    return make


def _sql(statement: str) -> str:
    return statement.replace("%", "%%").replace("?", "%s")


def _param(value: Any) -> Any:
    if isinstance(value, bool):     # SQLite stores these as integers and the columns stay INTEGER
        return int(value)
    if isinstance(value, str):      # Postgres text cannot hold NUL, which extracted documents can contain
        return value.replace("\x00", "")
    return value


class Session:
    def __init__(self, conn) -> None:
        self.conn = conn

    def bind(self, org: str) -> None:
        """RLS reads this. Skips the round trip when the pooled connection already has it."""
        if getattr(self.conn, "_vyuham_org", None) != org:
            self.conn.execute("SELECT set_config('app.org_id', %s, false)", [org])
            self.conn._vyuham_org = org

    def execute(self, statement: str, params: Iterable[Any] = ()):
        return self.conn.execute(_sql(statement), [_param(p) for p in params])

    def executemany(self, statement: str, seq: Iterable[Iterable[Any]]) -> None:
        with self.conn.cursor() as cur:
            cur.executemany(_sql(statement), [[_param(p) for p in params] for params in seq])


_pool: Optional[ConnectionPool] = None
_schema = ""
_local = threading.local()


def open_pool(url: str, schema: str) -> None:
    global _pool, _schema
    if not re.fullmatch(r"[a-z_][a-z0-9_]*", schema):
        raise RuntimeError("VYUHAM_SCHEMA may only contain lowercase letters, numbers and underscores")
    # Driver errors can echo a malformed URL, password included, so reject those before connecting.
    authority = re.match(r"^postgres(?:ql)?://([^/]*)/", url)
    if not authority or authority.group(1).count("@") != 1:
        raise RuntimeError("SUPABASE_DB_URL is malformed. Symbols in the password must be percent-encoded.")
    _schema = schema

    def configure(conn) -> None:    # startup options do not survive the pooler, so set this per connection
        conn.execute(f'SET search_path TO "{schema}"')

    _pool = ConnectionPool(url, min_size=1, max_size=10, timeout=30, open=False, configure=configure,
                           kwargs={"autocommit": True, "prepare_threshold": None, "row_factory": _row_factory})
    _pool.open(wait=True, timeout=30)
    atexit.register(close_pool)


def close_pool() -> None:
    global _pool
    if _pool is not None:
        _pool.close()
        _pool = None


@contextmanager
def session():
    from . import db
    held = getattr(_local, "session", None)
    if held is not None:
        held.bind(db.org())
        yield held
        return
    with _pool.connection() as conn:
        _local.session = Session(conn)
        _local.session.bind(db.org())
        try:
            yield _local.session
        finally:
            _local.session = None


@contextmanager
def transaction():
    with session() as s, s.conn.transaction():
        yield s


def migrate(backup: Callable[[str], Path], owner_url: str = "") -> None:
    """Applies pending migrations, each committed together with its version row. The app's own role cannot change the schema."""
    import psycopg
    conn = psycopg.connect(owner_url, autocommit=True, prepare_threshold=None, row_factory=_row_factory) if owner_url else _pool.getconn()
    owner = Session(conn)
    try:
        with conn.transaction():
            owner.execute("SELECT pg_advisory_xact_lock(?)", (_MIGRATION_LOCK,))
            conn.execute(f'CREATE SCHEMA IF NOT EXISTS "{_schema}"')
            conn.execute(f'SET search_path TO "{_schema}"')
            exists = conn.execute("SELECT to_regclass('schema_migrations') IS NOT NULL").fetchone()[0]
            if not exists:
                if owner_url or conn.execute("SELECT has_schema_privilege(current_user, current_schema(), 'CREATE')").fetchone()[0]:
                    owner.execute("CREATE TABLE schema_migrations (version INTEGER PRIMARY KEY, applied_at TEXT NOT NULL)")
            applied = {r[0] for r in owner.execute("SELECT version FROM schema_migrations").fetchall()}
            pending = [(v, script) for v, script in enumerate(MIGRATIONS, start=1) if v not in applied]
            if applied and pending:     # a new database has nothing to protect
                backup("pre-migration", owner)
        for version, script in pending:
            with conn.transaction():
                owner.execute("SELECT pg_advisory_xact_lock(?)", (_MIGRATION_LOCK,))
                if owner.execute("SELECT 1 FROM schema_migrations WHERE version = ?", (version,)).fetchone():
                    continue    # another process applied it while this one waited
                conn.execute(script)
                owner.execute("INSERT INTO schema_migrations VALUES (?, ?)", (version, utcnow()))
    finally:
        if owner_url:
            conn.close()
        else:
            _pool.putconn(conn)


def dump_tables(dest: Path, owner: Optional[Session] = None) -> None:
    """Writes every table's rows to JSON. The schema itself is in MIGRATIONS. Without an owner session it holds only the current company's rows."""
    with (nullcontext(owner) if owner else session()) as s:
        tables = [r[0] for r in s.execute("SELECT tablename FROM pg_tables WHERE schemaname = ?", (_schema,)).fetchall()]
        for table in tables:
            rows = [dict(r) for r in s.execute(f'SELECT * FROM "{table}"').fetchall()]
            (dest / f"{table}.json").write_text(json.dumps(rows, default=str), encoding="utf-8")


def drop_schema_for_tests(schema: str, owner_url: str) -> None:
    if not schema.startswith("vyuham_test_"):
        raise RuntimeError("Refusing to drop a schema that is not a test schema")
    import psycopg
    with psycopg.connect(owner_url, autocommit=True, prepare_threshold=None) as conn:
        conn.execute(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE')
